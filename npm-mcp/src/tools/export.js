/**
 * thor_export — Render validation_summary.md to self-contained HTML.
 * Inlines CSS, shows pass/fail with colors, shareable as a single file.
 */

import { readFileSync, writeFileSync, existsSync } from "fs";
import { join, dirname } from "path";

/**
 * Convert markdown summary to styled HTML.
 */
function markdownToHtml(md) {
  let html = md;

  // Escape HTML entities in code blocks first
  html = html.replace(/```\n?([\s\S]*?)```/g, (_, code) => {
    const escaped = code.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
    return `<pre><code>${escaped}</code></pre>`;
  });

  // Headers
  html = html.replace(/^### (.+)$/gm, "<h3>$1</h3>");
  html = html.replace(/^## (.+)$/gm, "<h2>$1</h2>");
  html = html.replace(/^# (.+)$/gm, "<h1>$1</h1>");

  // Bold
  html = html.replace(/\*\*(.+?)\*\*/g, "<strong>$1</strong>");

  // List items
  html = html.replace(/^- (.+)$/gm, "<li>$1</li>");
  html = html.replace(/(<li>.*<\/li>\n?)+/g, (match) => `<ul>${match}</ul>`);

  // Horizontal rules
  html = html.replace(/^---$/gm, "<hr>");

  // Paragraphs (lines not already wrapped)
  html = html.replace(/^(?!<[huplo]|<\/|<hr|<pre)(.+)$/gm, "<p>$1</p>");

  // Newlines
  html = html.replace(/\n\n+/g, "\n");

  return html;
}

/**
 * Inject pass/fail coloring into control sections.
 */
function colorizeControls(html) {
  // Color passed controls green
  html = html.replace(
    /(<h2>Passed Controls<\/h2>)([\s\S]*?)(?=<h2>|<hr|$)/g,
    (_, header, content) => `${header}<div class="passed-section">${content}</div>`
  );

  // Color failed controls red
  html = html.replace(
    /(<h2>Failed Controls<\/h2>)([\s\S]*?)(?=<h2>|<hr|$)/g,
    (_, header, content) => `${header}<div class="failed-section">${content}</div>`
  );

  // Color waived controls amber
  html = html.replace(
    /(<h2>Waived Controls<\/h2>)([\s\S]*?)(?=<h2>|<hr|$)/g,
    (_, header, content) => `${header}<div class="waived-section">${content}</div>`
  );

  return html;
}

