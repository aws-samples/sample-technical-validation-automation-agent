/**
 * Export validation summary to HTML.
 */
export function exportHtml(partnerFolder, outputPath) {
  const summaryPath = join(partnerFolder, "validation_summary.md");

  if (!existsSync(summaryPath)) {
    throw new Error(`No validation_summary.md found in ${partnerFolder}. Run thor_validate first.`);
  }

  const md = readFileSync(summaryPath, "utf-8");
  let bodyHtml = markdownToHtml(md);
  bodyHtml = colorizeControls(bodyHtml);

  const fullHtml = `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>Thor PSA Validation Report</title>
  ${CSS}
</head>
<body>
  ${bodyHtml}
  <footer style="margin-top:2rem;padding-top:1rem;border-top:1px solid #dee2e6;color:#6c757d;font-size:0.8rem;">
    Generated by Thor PSA Validator &mdash; ${new Date().toISOString()}
  </footer>
</body>
</html>`;

  const outPath = outputPath || join(partnerFolder, "validation_report.html");
  writeFileSync(outPath, fullHtml, "utf-8");

  return `Exported HTML report to: ${outPath}`;
}
