func writeReport(t *testing.T, dir, ts string, results []validator.Result) string {
	t.Helper()
	path := filepath.Join(dir, "validation_summary_"+ts+".md")
	body := RenderMarkdown(Summary{
		PartnerName: "P",
		Timestamp:   time.Date(2026, 5, 13, 10, 30, 0, 0, time.UTC),
		Results:     results,
	})
	if err := os.WriteFile(path, []byte(body), 0o600); err != nil {
		t.Fatal(err)
	}
	return path
}

func TestParseSummary_RoundTrip(t *testing.T) {
	dir := t.TempDir()
	path := writeReport(t, dir, "20260513_103000", []validator.Result{
		{ControlID: "ACCT-001", Status: validator.StatusPassed, Reasoning: "ok"},
		{ControlID: "DOC-006", Status: validator.StatusFailed, Reasoning: "missing"},
	})

	got, err := ParseSummary(path)
	if err != nil {
		t.Fatal(err)
	}
	if got["ACCT-001"].Status != "PASS" || got["ACCT-001"].Reasoning != "ok" {
		t.Errorf("ACCT-001: %+v", got["ACCT-001"])
	}
	if got["DOC-006"].Status != "FAIL" || got["DOC-006"].Reasoning != "missing" {
		t.Errorf("DOC-006: %+v", got["DOC-006"])
	}
}

func TestRenderDiff_StatusChangeHighlighted(t *testing.T) {
	r1 := map[string]ParsedResult{
		"ACCT-001": {Status: "PASS", Reasoning: "good v1"},
		"DOC-006":  {Status: "FAIL", Reasoning: "missing v1"},
	}
	r2 := map[string]ParsedResult{
		"ACCT-001": {Status: "PASS", Reasoning: "good v2"},
		"DOC-006":  {Status: "PASS", Reasoning: "fixed it"},
	}
	got := RenderDiff("Acme", "20260101", "20260102", r1, r2)

	for _, want := range []string{
		"# Validation Diff — Acme",
		"`20260101` (2 controls) → `20260102` (2 controls)",
		"**Changed:** 1 | **Unchanged Pass:** 1 | **Unchanged Fail:** 0",
		"### DOC-006: FAIL → PASS",
		"**Previous reasoning:** missing v1",
		"**Current reasoning:** fixed it",
		"## Still Passing (1 controls)",
		"ACCT-001",
	} {
		if !strings.Contains(got, want) {
			t.Errorf("diff missing %q\n%s", want, got)
		}
	}
}

func TestRenderDiff_NewAndRemovedControls(t *testing.T) {
	r1 := map[string]ParsedResult{
		"GONE-001": {Status: "PASS"},
	}
	r2 := map[string]ParsedResult{
		"NEW-001": {Status: "FAIL"},
	}
	got := RenderDiff("Acme", "ts1", "ts2", r1, r2)
	if !strings.Contains(got, "## New in latest run (1 controls)") {
		t.Error("missing new-section heading")
	}
	if !strings.Contains(got, "- NEW-001: FAIL") {
		t.Error("missing NEW-001 row")
	}
	if !strings.Contains(got, "## Not in latest run (1 controls)") {
		t.Error("missing removed-section heading")
	}
	if !strings.Contains(got, "- GONE-001 (was PASS)") {
		t.Error("missing removed row")
	}
}

