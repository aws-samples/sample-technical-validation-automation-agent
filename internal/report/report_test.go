func TestFindReport_FuzzyMatch(t *testing.T) {
	reports := []ReportFile{
		{Path: "/x/validation_summary_20260101_080000.md", Timestamp: "20260101_080000"},
		{Path: "/x/validation_summary_20260102_090000.md", Timestamp: "20260102_090000"},
	}
	if r := FindReport(reports, "20260102"); r == nil || r.Timestamp != "20260102_090000" {
		t.Errorf("fuzzy match failed: %+v", r)
	}
	if r := FindReport(reports, ""); r != nil {
		t.Error("empty input must return nil")
	}
	if r := FindReport(reports, "no-such-thing"); r != nil {
		t.Error("non-matching input must return nil")
	}
}
