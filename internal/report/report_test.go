func TestRenderHTML_HasSelfContainedShell(t *testing.T) {
	html := RenderHTML("# title\n\n## section\n", "ExamplePartner")
	for _, want := range []string{
		"<!DOCTYPE html>",
		`<title>Validation Report — ExamplePartner</title>`,
		"<h1>title</h1>",
		"<h2>section</h2>",
		"Generated by Thor CLI",
	} {
		if !strings.Contains(html, want) {
			t.Errorf("HTML missing %q", want)
		}
	}
}

func TestRenderHTML_EscapesUserContent(t *testing.T) {
	got := RenderHTML("# <script>alert(1)</script>\n", "Acme & Co")
	if strings.Contains(got, "<script>alert(1)</script>") {
		t.Error("user content was not HTML-escaped in body")
	}
	if strings.Contains(got, "Acme & Co<") {
		// We expect Acme &amp; Co in the title.
		t.Error("partner name was not HTML-escaped in title")
	}
	if !strings.Contains(got, "Acme &amp; Co") {
		t.Error("partner name should be escaped to Acme &amp; Co")
	}
}

func TestRenderHTML_HandlesCodeFenceAndBold(t *testing.T) {
	md := "# h\n\n**bold line**\n\nplain with **inline bold** here\n\n```\ncode <here>\n```\n"
	got := RenderHTML(md, "P")
	if !strings.Contains(got, "<p><strong>bold line</strong></p>") {
		t.Error("missing whole-line bold")
	}
	if !strings.Contains(got, "plain with <strong>inline bold</strong> here") {
		t.Error("missing inline bold substitution")
	}
	if !strings.Contains(got, "<pre>") || !strings.Contains(got, "</pre>") {
		t.Error("code fence was not wrapped in <pre>")
	}
	if !strings.Contains(got, "code &lt;here&gt;") {
		t.Error("code-block contents must be HTML-escaped")
	}
}

func TestRenderHTML_HorizontalRule(t *testing.T) {
	got := RenderHTML("a\n\n---\n\nb\n", "P")
	if !strings.Contains(got, "<hr>") {
		t.Error("missing <hr>")
	}
}

